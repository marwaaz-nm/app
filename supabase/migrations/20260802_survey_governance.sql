CREATE POLICY "Authorized users can insert surveys" ON public.surveys
  FOR INSERT TO authenticated WITH CHECK (public.has_action('survey.create'));
CREATE POLICY "Authorized users can edit surveys" ON public.surveys
  FOR UPDATE TO authenticated USING (public.has_action('survey.edit')) WITH CHECK (public.has_action('survey.edit'));
CREATE POLICY "Admins can delete surveys" ON public.surveys
  FOR DELETE TO authenticated USING (public.is_admin());

-- All survey mutations go through the authenticated server API. This prevents
-- callers from bypassing workflow transitions by talking to PostgREST directly.
REVOKE INSERT, UPDATE, DELETE ON public.surveys FROM authenticated;

-- The original self-update profile policy otherwise allows a user to grant
-- themselves actions or an Admin role. Profile writes are server-admin only.
REVOKE UPDATE ON public.profiles FROM authenticated;

