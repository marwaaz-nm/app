CREATE OR REPLACE FUNCTION public.is_admin(check_uid UUID DEFAULT auth.uid())
RETURNS BOOLEAN LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.profiles
    WHERE id = check_uid AND role = 'Admin'
  );
$$;

CREATE OR REPLACE FUNCTION public.has_action(action_name TEXT, check_uid UUID DEFAULT auth.uid())
RETURNS BOOLEAN LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT public.is_admin(check_uid) OR EXISTS (
    SELECT 1 FROM public.profiles
    WHERE id = check_uid AND action_name = ANY(COALESCE(permitted_actions, ARRAY[]::TEXT[]))
  );
$$;

CREATE OR REPLACE FUNCTION public.polygon_text_to_geometry(poly_text TEXT)
RETURNS geometry LANGUAGE plpgsql IMMUTABLE AS $$
DECLARE
  ring geometry;
BEGIN
  IF poly_text IS NULL OR btrim(poly_text) = '' THEN RETURN NULL; END IF;
  IF EXISTS (
    SELECT 1
    FROM unnest(string_to_array(poly_text, ';')) AS p(raw_point)
    WHERE btrim(raw_point) = ''
      OR split_part(raw_point, ',', 1)::DOUBLE PRECISION NOT BETWEEN -90 AND 90
      OR split_part(raw_point, ',', 2)::DOUBLE PRECISION NOT BETWEEN -180 AND 180
  ) THEN RETURN NULL; END IF;
  SELECT ST_MakeLine(ARRAY_AGG(ST_SetSRID(ST_MakePoint(
    split_part(point_text, ',', 2)::DOUBLE PRECISION,
    split_part(point_text, ',', 1)::DOUBLE PRECISION
  ), 4326) ORDER BY ordinal))
  INTO ring
  FROM unnest(string_to_array(poly_text, ';')) WITH ORDINALITY AS p(raw_point, ordinal)
  CROSS JOIN LATERAL (SELECT btrim(raw_point) AS point_text) clean;

  IF ST_NPoints(ring) < 3 THEN RETURN NULL; END IF;
  IF NOT ST_Equals(ST_StartPoint(ring), ST_EndPoint(ring)) THEN
    ring := ST_AddPoint(ring, ST_StartPoint(ring));
  END IF;
  IF NOT ST_IsValid(ST_MakePolygon(ring)) THEN RETURN NULL; END IF;
  RETURN ST_MakePolygon(ring);
EXCEPTION WHEN OTHERS THEN
  RETURN NULL;
END;
$$;

CREATE OR REPLACE FUNCTION public.sync_survey_geometry()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  NEW.geom := public.polygon_text_to_geometry(NEW.polygon_boundary);
  NEW.updated_at := CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS surveys_sync_geometry ON public.surveys;
CREATE TRIGGER surveys_sync_geometry
  BEFORE INSERT OR UPDATE OF polygon_boundary ON public.surveys
  FOR EACH ROW EXECUTE FUNCTION public.sync_survey_geometry();

UPDATE public.surveys
SET geom = public.polygon_text_to_geometry(polygon_boundary)
WHERE polygon_boundary IS NOT NULL AND geom IS NULL;

CREATE INDEX IF NOT EXISTS surveys_geom_gix ON public.surveys USING GIST (geom);

CREATE OR REPLACE FUNCTION public.check_survey_overlap(poly_text TEXT, exclude_survey_id BIGINT DEFAULT NULL)
RETURNS TABLE(id BIGINT, serial_no INTEGER, owner_name VARCHAR, overlap_area_m2 DOUBLE PRECISION)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  WITH candidate AS (SELECT public.polygon_text_to_geometry(poly_text) AS geom)
  SELECT s.id, s.serial_no, s.owner_name,
    ST_Area(ST_Intersection(s.geom, c.geom)::geography) AS overlap_area_m2
  FROM public.surveys s CROSS JOIN candidate c
  WHERE c.geom IS NOT NULL
    AND s.geom IS NOT NULL
    AND (exclude_survey_id IS NULL OR s.id <> exclude_survey_id)
    AND s.status <> 'Archived'
    AND ST_Intersects(s.geom, c.geom)
    AND ST_Area(ST_Intersection(s.geom, c.geom)::geography) > 0.05
  ORDER BY overlap_area_m2 DESC;
$$;

CREATE OR REPLACE FUNCTION public.is_survey_polygon_valid(poly_text TEXT)
RETURNS BOOLEAN LANGUAGE sql IMMUTABLE AS $$
  SELECT public.polygon_text_to_geometry(poly_text) IS NOT NULL;
$$;

CREATE OR REPLACE FUNCTION public.audit_survey_change()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  actor UUID := COALESCE(NEW.updated_by, auth.uid());
BEGIN
  IF TG_OP = 'INSERT' THEN
    INSERT INTO public.survey_revisions(survey_id, version, action, notes, survey_snapshot, changed_by)
    VALUES (NEW.id, NEW.version, 'Created', 'Survey created', to_jsonb(NEW) - 'geom', COALESCE(NEW.created_by, actor));
    RETURN NEW;
  END IF;

  IF to_jsonb(OLD) IS DISTINCT FROM to_jsonb(NEW) THEN
    INSERT INTO public.survey_revisions(survey_id, version, action, notes, survey_snapshot, changed_fields, changed_by)
    VALUES (
      OLD.id, OLD.version, CASE WHEN OLD.status IS DISTINCT FROM NEW.status THEN 'Status Changed' ELSE 'Updated' END,
      CASE WHEN OLD.status IS DISTINCT FROM NEW.status THEN OLD.status || ' -> ' || NEW.status ELSE 'Survey details updated' END,
      to_jsonb(OLD) - 'geom',
      jsonb_build_object('before', to_jsonb(OLD) - 'geom', 'after', to_jsonb(NEW) - 'geom'),
      actor
    );
  END IF;
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.bump_survey_version()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  NEW.version := OLD.version + 1;
  NEW.updated_at := CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS surveys_bump_version ON public.surveys;
CREATE TRIGGER surveys_bump_version
  BEFORE UPDATE ON public.surveys
  FOR EACH ROW EXECUTE FUNCTION public.bump_survey_version();

DROP TRIGGER IF EXISTS surveys_audit_change ON public.surveys;
CREATE TRIGGER surveys_audit_change
  AFTER INSERT OR UPDATE ON public.surveys
  FOR EACH ROW EXECUTE FUNCTION public.audit_survey_change();

