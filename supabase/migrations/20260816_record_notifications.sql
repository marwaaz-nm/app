-- Per-user record notifications. A notification row is created only for staff who can
-- open the corresponding menu, so RLS and menu permissions agree by construction.
CREATE TABLE IF NOT EXISTS public.app_notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recipient_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  menu_path TEXT NOT NULL,
  entity_type TEXT NOT NULL,
  entity_id BIGINT NOT NULL,
  title TEXT NOT NULL,
  body TEXT NOT NULL,
  href TEXT NOT NULL,
  read_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (recipient_id, entity_type, entity_id)
);

CREATE INDEX IF NOT EXISTS app_notifications_recipient_idx
  ON public.app_notifications(recipient_id, created_at DESC);

ALTER TABLE public.app_notifications ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Users can read their own notifications" ON public.app_notifications;
DROP POLICY IF EXISTS "Users can update their own notifications" ON public.app_notifications;
CREATE POLICY "Users can read their own notifications" ON public.app_notifications
  FOR SELECT TO authenticated USING (recipient_id = auth.uid());
CREATE POLICY "Users can update their own notifications" ON public.app_notifications
  FOR UPDATE TO authenticated USING (recipient_id = auth.uid())
  WITH CHECK (recipient_id = auth.uid());

CREATE OR REPLACE FUNCTION public.enqueue_menu_notification(
  target_menu TEXT,
  target_entity_type TEXT,
  target_entity_id BIGINT,
  notification_title TEXT,
  notification_body TEXT,
  target_href TEXT
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  INSERT INTO public.app_notifications(
    recipient_id, menu_path, entity_type, entity_id, title, body, href
  )
  SELECT
    profile.id,
    target_menu,
    target_entity_type,
    target_entity_id,
    notification_title,
    notification_body,
    target_href
  FROM public.profiles AS profile
  WHERE profile.role IN ('Admin', 'SuperAdmin')
     OR target_menu = ANY(COALESCE(profile.permitted_menus, ARRAY[]::TEXT[]))
  ON CONFLICT (recipient_id, entity_type, entity_id) DO NOTHING;

END;
$$;

CREATE OR REPLACE FUNCTION public.notify_new_survey_record()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  PERFORM public.enqueue_menu_notification(
    '/records', 'survey', NEW.id,
    'Survey cusub ayaa la diiwaangeliyey',
    'Survey ' || COALESCE(NEW.survey_no, NEW.serial_no::TEXT) || ' - ' || NEW.owner_name,
    '/records'
  );
  RETURN NEW;
END;
$$;

