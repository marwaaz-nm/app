-- Supabase Realtime delivers each recipient's new row immediately. Ignore the duplicate
-- object error when the table was already added to the publication manually.
DO $$
BEGIN
  ALTER PUBLICATION supabase_realtime ADD TABLE public.app_notifications;
EXCEPTION
  WHEN duplicate_object THEN NULL;
END $$;

GRANT SELECT, UPDATE ON public.app_notifications TO authenticated;
